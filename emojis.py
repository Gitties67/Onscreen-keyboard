# 8=D with any number of "=" (and 8=D~ for the splash)
_EGGPLANT = re.compile(r"8=+D(~*)$")


def emoticon(typed: str) -> tuple[str, str] | None:
    """(emoticon, emoji) when `typed` ends with an emoticon, longest first.
    One starting with a letter or digit ("XD", "B)"), or ":/" (as in
    "https://"), must not follow a letter or digit, so words don't match."""
    m = _EGGPLANT.search(typed)
    if m and (m.start() == 0 or not typed[m.start() - 1].isalnum()):
        return m.group(0), "🍆💦" if m.group(1) else "🍆"
    for size in (3, 2):
        face = typed[-size:]
        if len(face) < size or face not in EMOTICONS:
            continue
        before = typed[-size - 1:-size]
        if before.isalnum() and (face[0].isalnum() or face in (":/", ":-/")):
            continue
        return face, EMOTICONS[face]
    return None

