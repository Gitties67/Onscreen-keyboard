#!/usr/bin/env python3
"""Write version_info.txt (PyInstaller VSVersionInfo) from the VERSION file.

VERSION holds e.g. "v0.1.8"; the leading "v" is stripped and the numeric
parts are padded to a 4-part Windows file version. Also verifies that
keyboard.py's __version__ agrees with VERSION so they cannot drift.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_version() -> str:
    with open(os.path.join(ROOT, "VERSION"), encoding="utf-8") as f:
        return f.read().strip().lstrip("vV")


def four_part(ver: str) -> tuple:
    nums = []
    for part in re.split(r"[.\-+]", ver):
        m = re.match(r"\d+", part)
        if not m:
            break  # stop at first non-numeric part, e.g. "beta"
        nums.append(int(m.group()))
    if not nums:
        sys.exit(f"gen_version_info: cannot parse numeric version from {ver!r}")
    nums = (nums + [0, 0, 0, 0])[:4]
    return tuple(min(n, 65535) for n in nums)


def check_keyboard_version(ver: str) -> None:
    with open(os.path.join(ROOT, "keyboard.py"), encoding="utf-8") as f:
        m = re.search(r'^__version__\s*=\s*"([^"]+)"', f.read(), re.M)
    if not m:
        sys.exit("gen_version_info: __version__ not found in keyboard.py")
    if m.group(1).lstrip("vV") != ver:
        sys.exit(f"gen_version_info: VERSION ({ver}) != keyboard.py __version__ "
                 f"({m.group(1)}); update both.")


TEMPLATE = '''# UTF-8
# Generated by tools/gen_version_info.py -- do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={t},
    prodvers={t},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', 'Gitties67'),
         StringStruct('FileDescription', 'On-Screen Keyboard'),
         StringStruct('FileVersion', '{s}'),
         StringStruct('InternalName', 'OnScreenKeyboard'),
         StringStruct('LegalCopyright', 'MIT License'),
         StringStruct('OriginalFilename', 'OnScreenKeyboard.exe'),
         StringStruct('ProductName', 'On-Screen Keyboard'),
         StringStruct('ProductVersion', '{s}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
'''


def main() -> None:
    ver = read_version()
    check_keyboard_version(ver)
    t = four_part(ver)
    out = os.path.join(ROOT, "version_info.txt")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(TEMPLATE.format(t=t, s=".".join(map(str, t))))
    print(f"wrote {out} for version {ver} -> {'.'.join(map(str, t))}")


if __name__ == "__main__":
    main()
