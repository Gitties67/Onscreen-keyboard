def is_country_flag(char: str) -> bool:
    """A country's flag: two region letters (🇩🇪) or a tag sequence (England)."""
    return any(0x1F1E6 <= ord(c) <= 0x1F1FF or 0xE0000 <= ord(c) <= 0xE007F
               for c in char)


# Country flags can be switched off (Settings): Windows has no flag emoji, so
# most apps there show them as two letters ("DE").  The keyboard turns this
# on or off from its setting at startup.
_flags_on = True


def set_country_flags(on: bool) -> None:
    global _flags_on
    _flags_on = on


def offered() -> list[tuple[str, str, list[str]]]:
    """EMOJI_DATA without the country flags while they're switched off."""
    if _flags_on:
        return EMOJI_DATA
    return [e for e in EMOJI_DATA if not is_country_flag(e[0])]

# Build reverse lookup once at import time
_LOOKUP: dict[str, tuple[str, list[str]]] = {
    char: (name, kws) for char, name, kws in EMOJI_DATA
}


def search(query: str, n: int = 60) -> list[str]:
    """Return up to n emoji chars whose name or keywords contain query."""
    emoji = offered()
    q = (query or "").lower().strip()
    if not q:
        return [e[0] for e in emoji[:n]]
    results: list[str] = []
    for char, name, keywords in emoji:
        if q in name or any(q in kw for kw in keywords):
            results.append(char)
            if len(results) >= n:
                break
    return results


def suggest(word: str, n: int = 3) -> list[str]:
    """
    Return up to n emojis for the suggestion bar, ranked by match quality.

    Ranking (best first):
      1. Exact keyword match (remaining chars = 0)
      2. Name of the emoji starts with word (more "on-topic")
      3. Fewer remaining characters in the matched keyword
      4. Original EMOJI_DATA order as tiebreaker
    """
    w = word.lower().strip()
    if len(w) < 2:
        return []

    scored: list[tuple[int, int, int, str]] = []  # (exact, name_bonus, remaining, char)
    for idx, (char, name, keywords) in enumerate(offered()):
        best_remaining = None
        for kw in keywords:
            if w == kw:
                best_remaining = 0
                break
            if len(w) >= 3 and kw.startswith(w):
                rem = len(kw) - len(w)
                if best_remaining is None or rem < best_remaining:
                    best_remaining = rem
        if best_remaining is None:
            continue
        exact      = 0 if best_remaining == 0 else 1   # lower = better
        name_bonus = 0 if name.startswith(w) else 1    # lower = better
        scored.append((exact, name_bonus, best_remaining, char))

    scored.sort(key=lambda t: (t[0], t[1], t[2]))
    return [char for _, _, _, char in scored[:n]]


